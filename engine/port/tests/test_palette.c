int test_palette(void)
{
    const char *world_path = getenv("YT2_WORLD");
    yt2_world world;
    yt2_palette palette;
    uint8_t base[YT2_WORLD_ANIM_SIZE];

    CHECK(yt2_palette_rotate(NULL, anim_base, 0u) == YT2_STATUS_ERROR);
    CHECK(yt2_palette_rotate(&palette, NULL, 0u) == YT2_STATUS_ERROR);
    CHECK(yt2_world_anim_base(NULL, base) == YT2_STATUS_ERROR);

    if (world_path == NULL || world_path[0] == '\0') {
        return 0;
    }
    CHECK(yt2_world_load(world_path, &world) == YT2_STATUS_OK);
    CHECK(yt2_world_anim_base(&world, base) == YT2_STATUS_OK);
    CHECK(memcmp(base, anim_base, sizeof(base)) == 0);
    CHECK(yt2_world_anim_base(&world, NULL) == YT2_STATUS_ERROR);

    for (unsigned int phase = 0; phase < YT2_PALETTE_ANIM_PHASES; phase++) {
        memset(palette.rgb, 0xAA, sizeof(palette.rgb));
        CHECK(yt2_palette_rotate(&palette, base, phase) == YT2_STATUS_OK);
        CHECK(memcmp(palette.rgb +
                         YT2_PALETTE_ANIM_FIRST * YT2_PALETTE_ENTRY_SIZE,
                     anim_phases[phase], YT2_WORLD_ANIM_SIZE) == 0);
        /* Everything outside D0h..DFh stays put. */
        for (unsigned int i = 0; i < YT2_PALETTE_SIZE; i++) {
            if (i < YT2_PALETTE_ANIM_FIRST * YT2_PALETTE_ENTRY_SIZE ||
                i >= (YT2_PALETTE_ANIM_FIRST + 16u) *
                         YT2_PALETTE_ENTRY_SIZE) {
                CHECK(palette.rgb[i] == 0xAAu);
            }
        }
    }

    /* The phase wraps modulo 4. */
    memset(palette.rgb, 0, sizeof(palette.rgb));
    CHECK(yt2_palette_rotate(&palette, base, 4u) == YT2_STATUS_OK);
    CHECK(memcmp(palette.rgb +
                     YT2_PALETTE_ANIM_FIRST * YT2_PALETTE_ENTRY_SIZE,
                 anim_phases[0], YT2_WORLD_ANIM_SIZE) == 0);
    CHECK(yt2_palette_rotate(&palette, base, 7u) == YT2_STATUS_OK);
    CHECK(memcmp(palette.rgb +
                     YT2_PALETTE_ANIM_FIRST * YT2_PALETTE_ENTRY_SIZE,
                 anim_phases[3], YT2_WORLD_ANIM_SIZE) == 0);

    yt2_world_free(&world);
    return 0;
}
