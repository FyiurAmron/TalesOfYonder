/*
 * The animation base as the game reads it (WORLD.DAT 82EBA, 48 bytes: four
 * groups of four DAC entries).  The last byte is 0x11, not palette 0's
 * 0x1B: the base is its own record, not a slice of the loaded palette.
 */
